"""HTTP status: class and reason phrase. Mirrors web/src/core/response/status.ts."""

from ..js import trim


def status_class(status: int) -> str:
    if status < 200:
        return "informational"
    if status < 300:
        return "success"
    if status < 400:
        return "redirect"
    if status < 500:
        return "clientError"
    return "serverError"


